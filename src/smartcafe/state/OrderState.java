package smartcafe.state;

/**
 * ============================================================================
 * [STATE PATTERN] - State Interface
 * ระบบการจัดการวงจรชีวิตออเดอร์ (Order Lifecycle Subsystem)
 * ----------------------------------------------------------------------------
 * ความเหมาะสมกับร้าน: เหมาะสมที่สุดในการควบคุมสถานะของเครื่องดื่มในร้าน
 * ตั้งแต่รับออเดอร์ -> ชำระเงิน -> เข้าครัวชง -> พร้อมรับ -> ส่งมอบ -> ยกเลิก
 * ป้องกันการกระทำผิดขั้นตอน (เช่น ยังไม่จ่ายเงินแต่ไปชง หรือ ชงเสร็จแล้วแต่ขอยกเลิก)
 * โดยไม่ต้องพึ่ง if-else มหาศาล
 * ============================================================================
 */
public interface OrderState {
    void next(OrderContext context);
    void cancel(OrderContext context);
    String getStateName();
    String getDescription();
}
